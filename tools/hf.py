#!/usr/bin/env python3
"""Bring a Higgsfield clip (generated through the Higgsfield MCP connector) into a video's media folder.

  python tools/hf.py get <result-url> --dir videos/<date>/media --name launch
      -> media/launch.mp4 (1080p H.264, no audio, ~3 MB for 5 s) and prints the params to paste:
         {"video": "media/launch.mp4", "url": "<result-url>", "ai": true, "credit": "..."}

If the download is blocked (the Claude cloud sandbox cannot reach Higgsfield's CDN), just put those
params in the script anyway: build.py downloads params.url on first use (works in GitHub Actions)
and previews use a placeholder.

Clips are generated by the session itself (Higgsfield MCP: generate_video / generate_video_batch,
Kling 3.0 pro, 16:9, sound off); this tool only downloads and normalises the result.
"""
import argparse
import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

CREDIT = "Yapay zekâ ile üretilmiş temsili görüntü: Higgsfield ({model})"


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("get")
    g.add_argument("url")
    g.add_argument("--dir", required=True)
    g.add_argument("--name", required=True)
    g.add_argument("--model", default="Kling 3.0")
    a = ap.parse_args()

    out = fetch(a.url, Path(a.dir) / f"{a.name}.mp4")
    rel = f"media/{out.name}"
    print(out, f"{out.stat().st_size / 1e6:.1f} MB", file=sys.stderr)
    print(json.dumps({"video": rel, "url": a.url, "ai": True, "credit": CREDIT.format(model=a.model)},
                     ensure_ascii=False))


def fetch(url, out):
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        raw = Path(tmp) / "raw.mp4"
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=120) as r:
            raw.write_bytes(r.read())
        # studio "photo" shots extract frames themselves; keep the file small and audio-free
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(raw), "-an",
                        "-vf", "scale=1920:1080:force_original_aspect_ratio=increase,crop=1920:1080",
                        "-c:v", "libx264", "-preset", "slow", "-crf", "20", "-pix_fmt", "yuv420p",
                        "-movflags", "+faststart", str(out)], check=True)
    return out


if __name__ == "__main__":
    main()
